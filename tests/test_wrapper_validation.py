# ---------------------------------------------------------------------------
# C Header validation
# ---------------------------------------------------------------------------


class TestCHeaderValidation:
    """Validate structural properties of generated C headers."""

    def test_include_guard_present(self):
        assert "#ifndef SAFE_ADD_H" in SAMPLE_C_HEADER
        assert "#define SAFE_ADD_H" in SAMPLE_C_HEADER
        assert "#endif" in SAMPLE_C_HEADER

    def test_include_guard_pattern(self):
        """Include guard follows #ifndef NAME_H / #define NAME_H pattern."""
        match = re.search(r"#ifndef\s+(\w+_H)\s*\n#define\s+(\w+_H)", SAMPLE_C_HEADER)
        assert match is not None
        assert match.group(1) == match.group(2)

    def test_stdint_included(self):
        assert "#include <stdint.h>" in SAMPLE_C_HEADER

    def test_function_declaration_present(self):
        assert re.search(r"int64_t\s+safe_add\s*\(", SAMPLE_C_HEADER) is not None

    def test_extern_c_block(self):
        assert 'extern "C"' in SAMPLE_C_HEADER

    def test_doxygen_pre_post(self):
        """Doxygen @pre and @post annotations are present."""
        assert "@pre" in SAMPLE_C_HEADER
        assert "@post" in SAMPLE_C_HEADER

    def test_multi_atom_header_has_all_functions(self):
        """Multi-atom header declares all functions."""
        assert re.search(r"int64_t\s+calc_subtotal\s*\(", SAMPLE_C_HEADER_MULTI)
        assert re.search(r"int64_t\s+calc_tax\s*\(", SAMPLE_C_HEADER_MULTI)
        assert re.search(r"int64_t\s+calc_total\s*\(", SAMPLE_C_HEADER_MULTI)

    def test_multi_atom_header_single_guard(self):
        """Multi-atom header has exactly one include guard pair."""
        ifndef_count = SAMPLE_C_HEADER_MULTI.count("#ifndef")
        define_count = SAMPLE_C_HEADER_MULTI.count("#define PAYMENT_H")
        assert ifndef_count == 1
        assert define_count == 1


