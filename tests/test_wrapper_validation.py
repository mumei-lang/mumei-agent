class TestRustWrapperValidation:
    """Validate structural properties of generated Rust wrappers."""

    def test_extern_c_block_present(self):
        assert 'extern "C"' in SAMPLE_RUST_WRAPPER

    def test_function_in_extern_block(self):
        """FFI function declared inside extern "C" block."""
        # Match: fn <name>(...) -> <type>;  inside extern "C" { ... }
        extern_block = re.search(
            r'extern\s+"C"\s*\{(.*?)\}',
            SAMPLE_RUST_WRAPPER,
            re.DOTALL,
        )
        assert extern_block is not None
        assert "fn safe_add" in extern_block.group(1)

    def test_safe_wrapper_present(self):
        """Safe (checked) wrapper function exists."""
        assert "pub fn safe_add_checked" in SAMPLE_RUST_WRAPPER

    def test_unsafe_call_in_wrapper(self):
        """Safe wrapper uses unsafe block to call FFI function."""
        assert "unsafe { safe_add(" in SAMPLE_RUST_WRAPPER

    def test_option_return_type(self):
        """Safe wrapper returns Option<i64>."""
        assert "-> Option<i64>" in SAMPLE_RUST_WRAPPER

    def test_multi_atom_extern_block(self):
        """Multi-atom wrapper has all functions in extern block."""
        extern_block = re.search(
            r'extern\s+"C"\s*\{(.*?)\}',
            SAMPLE_RUST_WRAPPER_MULTI,
            re.DOTALL,
        )
        assert extern_block is not None
        block_content = extern_block.group(1)
        assert "fn calc_subtotal" in block_content
        assert "fn calc_tax" in block_content
        assert "fn calc_total" in block_content

    def test_multi_atom_safe_wrappers(self):
        """Each atom has a safe wrapper function."""
        assert "pub fn calc_subtotal_checked" in SAMPLE_RUST_WRAPPER_MULTI
        assert "pub fn calc_tax_checked" in SAMPLE_RUST_WRAPPER_MULTI
        assert "pub fn calc_total_checked" in SAMPLE_RUST_WRAPPER_MULTI


