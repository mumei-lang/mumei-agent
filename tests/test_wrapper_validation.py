"""Static validation tests for generated FFI wrappers (SI-3 verification).

These tests validate the *content* of generated C headers, Rust wrappers,
and Python wrappers without requiring the mumei binary.  They check
structural properties that any correct emit output must satisfy.

Run with: pytest tests/test_wrapper_validation.py
"""
from __future__ import annotations

import re
import textwrap



