# ---------------------------------------------------------------------------
# Cross-wrapper consistency checks
# ---------------------------------------------------------------------------


class TestCrossWrapperConsistency:
    """Verify consistency across C, Rust, and Python wrappers."""

    def test_function_name_consistency(self):
        """Same function name appears in all three wrappers."""
        assert "safe_add" in SAMPLE_C_HEADER
        assert "safe_add" in SAMPLE_RUST_WRAPPER
        assert "safe_add" in SAMPLE_PYTHON_WRAPPER

    def test_parameter_count_consistency(self):
        """All wrappers declare the same number of parameters."""
        # C: int64_t safe_add(int64_t a, int64_t b)
        c_params = re.search(r"safe_add\((.*?)\)", SAMPLE_C_HEADER)
        assert c_params is not None
        c_count = c_params.group(1).count(",") + 1

        # Rust: fn safe_add(a: i64, b: i64)
        rust_params = re.search(r"fn safe_add\((.*?)\)", SAMPLE_RUST_WRAPPER)
        assert rust_params is not None
        rust_count = rust_params.group(1).count(",") + 1

        # Python: def safe_add(a: int, b: int)
        py_params = re.search(r"def safe_add\((.*?)\)", SAMPLE_PYTHON_WRAPPER)
        assert py_params is not None
        # Exclude self parameter if present
        py_count = py_params.group(1).count(",") + 1

        assert c_count == rust_count == py_count == 2

    def test_multi_atom_function_count_consistency(self):
        """All multi-atom wrappers declare the same number of functions."""
        c_fns = len(re.findall(r"int64_t\s+\w+\s*\(", SAMPLE_C_HEADER_MULTI))
        rust_fns = len(re.findall(r"fn\s+calc_\w+\s*\(", SAMPLE_RUST_WRAPPER_MULTI))
        py_fns = len(re.findall(r"def\s+calc_\w+\s*\(", SAMPLE_PYTHON_WRAPPER_MULTI))

        assert c_fns == 3
        assert rust_fns >= 3  # Rust has both extern and safe wrappers
        assert py_fns == 3
