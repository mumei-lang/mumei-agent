class ScriptedGenerator:
    """Deterministic ``AiProofGenerator``: returns canned Lean per call."""

    def __init__(self, replies: list[str]) -> None:
        self.replies = list(replies)
        self.requests: list[dict] = []

    def generate_lean_proof(self, request: dict) -> str:
        self.requests.append(request)
        if not self.replies:
            raise RuntimeError("no scripted reply left")
        return self.replies.pop(0)


def _good_module(theorem: str = "square_nonneg_correct") -> str:
    """An LLM reply echoing the (fixed) statement plus a tactic script."""
    return (
        "```lean\n"
        f"theorem {theorem} (x : Int) (result : Int) (h_body : result = squareNonnegResult x) :\n"
        "    (True) → (result ≥ 0) := by\n"
        "  intro _\n  rw [h_body]\n  exact mul_self_nonneg x\n```"
    )


BRIDGE_MODULE = """import MumeiLean

/-!
# Generated.Ai_e2e

Auto-generated by `scripts/ingest_cert.py` for mumei module `ai_e2e`.
-/

namespace Generated.Ai_e2e

open MumeiLean

def squareNonnegResult (x : Int) : Int :=
  x * x

-- mumei_escalation_reason: z3_unknown_complex_fragment
/-- Auto-generated from mumei atom `square_nonneg`. -/
theorem square_nonneg_correct (x : Int) (result : Int) (h_body : result = squareNonnegResult x) :
    (True) → (result ≥ 0) := by
  rw [h_body]
  unfold squareNonnegResult
  mumei_arith_deep

theorem other_correct : True := by
  sorry

end Generated.Ai_e2e
"""


def _fake_repo(tmp_path: Path, *, with_statement: bool = True) -> Path:
    repo = tmp_path / "mumei-lean"
    (repo / "scripts").mkdir(parents=True)
    (repo / "scripts" / "bridge.py").write_text("# stub\n")
    (repo / "scripts" / "export_cert.py").write_text(
        'TRANSLATOR_VERSION = "mumei-lean-translator-ir-v1"\n'
        'BRIDGE_LEMMA_HASH = "hash-for-test"\n',
        encoding="utf-8",
    )
    (repo / "lakefile.lean").write_text("-- stub\n")
    if with_statement:
        generated = repo / "generated" / "Generated"
        generated.mkdir(parents=True)
        (generated / "Ai_e2e.lean").write_text(BRIDGE_MODULE, encoding="utf-8")
    return repo


def _cert() -> dict:
    return {
        "all_verified": False,
        "atoms": [
            {"name": "ok", "z3_check_result": "unsat"},
            {
                "name": "square_nonneg",
                "z3_check_result": "unknown",
                "z3_result_class": "unknown",
                "escalation_reason": "z3_unknown_complex_fragment",
                "requires": "true",
                "ensures": "result >= 0",
                "body_expr": "x * x",
            },
        ],
    }


def _lake_ok() -> tuple[int, str]:
    return 0, (
        "info: 'Generated.AiProof.Square_nonneg.square_nonneg_correct' depends on "
        "axioms: [propext, Classical.choice, Quot.sound]\n"
        "Build completed successfully.\n"
    )


def _lake_unsolved() -> tuple[int, str]:
    return 1, "\nerror: unsolved goals\nx : Int\n⊢ 0 ≤ x * x"


def _patch_lake(**kwargs):
    """Patch the AI stage's Lake runner (``(returncode, log)``)."""
    return patch("agent.lean_ai_proof._lake_build_module", **kwargs)


