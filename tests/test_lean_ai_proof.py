def test_extract_tactic_script_accepts_full_theorem_or_bare_tactics() -> None:
    assert extract_tactic_script(_good_module(), "square_nonneg_correct") == (
        "intro _\nrw [h_body]\nexact mul_self_nonneg x"
    )
    assert extract_tactic_script("```lean\n  simp\n  ring\n```", "t") == "simp\nring"
    assert extract_tactic_script("by\n  omega", "t") == "omega"
    # a *different* statement for the expected name is discarded: only the
    # tactic text survives, and it is spliced under the trusted header.
    assert extract_tactic_script(
        "theorem t_correct : True := by\n  trivial", "t_correct"
    ) == "trivial"


